function normalizePokemonName(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/♀/g, "-f")
    .replace(/♂/g, "-m")
    .replace(/[.’']/g, "")
    .toLowerCase()
    .replace(/^(?:mega|m|radiant|shining|dark|light|alolan|galarian|hisuian|paldean)\s+/g, "")
    .replace(/^.*?s\s+(?=[a-z0-9])/g, "")
    .replace(/\s+(?:ex|gx|v|vmax|vstar|break|lv\.?\s*x)$/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function getPokemonTypeFromName(
  name?: string
): PokemonType | undefined {
  if (typeof name !== "string" || !name.trim()) {
    return undefined;
  }

  const normalizedName = normalizePokemonName(name);
  const exactType = POKEMON_NAME_TYPES[normalizedName];

  if (exactType) {
    return exactType;
  }

  /*
   * Hjælper ejer- og specialnavne som "Hop's Zacian ex".
   * Det længste match vælges, så f.eks. Mr. Mime ikke
   * forveksles med et kortere navn.
   */
  const matchingName = Object.keys(POKEMON_NAME_TYPES)
    .filter(
      (pokemonName) =>
        normalizedName === pokemonName ||
        normalizedName.endsWith(`-${pokemonName}`)
    )
    .sort((first, second) => second.length - first.length)[0];

  return matchingName
    ? POKEMON_NAME_TYPES[matchingName]
    : undefined;
}
