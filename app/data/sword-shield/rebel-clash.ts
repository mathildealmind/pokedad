function getPokemonType(cardNumber: string): PokemonType | undefined {
  const number = Number.parseInt(cardNumber, 10);
  if ((number >= 1 && number <= 23) || (number >= 175 && number <= 176) || number === 193) return PokemonType.Grass;
  if ((number >= 24 && number <= 36) || (number >= 177 && number <= 178) || number === 194) return PokemonType.Fire;
  if ((number >= 37 && number <= 55) || (number >= 179 && number <= 180) || number === 195 || number === 205) return PokemonType.Water;
  if ((number >= 56 && number <= 73) || (number >= 181 && number <= 182) || number === 196) return PokemonType.Lightning;
  if ((number >= 74 && number <= 93) || number === 183 || number === 197) return PokemonType.Psychic;
  if ((number >= 94 && number <= 111) || (number >= 184 && number <= 185) || number === 198) return PokemonType.Fighting;
  if ((number >= 112 && number <= 125) || number === 186 || number === 199) return PokemonType.Darkness;
  if ((number >= 126 && number <= 140) || number === 187 || number === 200 || number === 206) return PokemonType.Metal;
  if ((number >= 141 && number <= 153) || number === 188) return PokemonType.Colorless;
  return undefined;
}

function createSlug(name: string, cardNumber: string): string {
  const normalizedName = name.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const number = cardNumber.split("/")[0].toLowerCase();
  return `${normalizedName}-${number}`;
}

