function getPokemonType(cardNumber: string): PokemonType | undefined {
  const number = Number.parseInt(cardNumber, 10);
  if ((number >= 1 && number <= 22) || (number >= 166 && number <= 167) || number === 186) return PokemonType.Grass;
  if ((number >= 23 && number <= 29) || number === 168) return PokemonType.Fire;
  if ((number >= 30 && number <= 42) || number === 169 || number === 187) return PokemonType.Water;
  if ((number >= 43 && number <= 62) || (number >= 170 && number <= 171) || number === 188) return PokemonType.Lightning;
  if ((number >= 63 && number <= 82) || number === 172) return PokemonType.Psychic;
  if ((number >= 83 && number <= 102) || (number >= 173 && number <= 174) || number === 189) return PokemonType.Fighting;
  if ((number >= 103 && number <= 111) || number === 175 || number === 198) return PokemonType.Darkness;
  if ((number >= 112 && number <= 129) || (number >= 176 && number <= 177) || number === 190) return PokemonType.Metal;
  if ((number >= 130 && number <= 145) || number === 178 || number === 191 || number === 199) return PokemonType.Colorless;
  return undefined;
}

function createSlug(name: string, cardNumber: string): string {
  const normalizedName = name.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const number = cardNumber.split("/")[0].toLowerCase();
  return `${normalizedName}-${number}`;
}

