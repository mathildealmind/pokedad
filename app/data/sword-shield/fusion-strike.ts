function getPokemonType(cardNumber: string): PokemonType | undefined {
  const number = Number.parseInt(cardNumber, 10);

  if ((number >= 1 && number <= 27) || number === 245 || number === 246 || number === 283) {
    return PokemonType.Grass;
  }
  if ((number >= 28 && number <= 49) || number === 247 || number === 265 || number === 284) {
    return PokemonType.Fire;
  }
  if ((number >= 50 && number <= 85) || number === 248 || number === 266) {
    return PokemonType.Water;
  }
  if ((number >= 86 && number <= 109) || number === 249 || number === 267 || number === 280) {
    return PokemonType.Lightning;
  }
  if ((number >= 110 && number <= 130) || (number >= 250 && number <= 251) || (number >= 268 && number <= 270)) {
    return PokemonType.Psychic;
  }
  if ((number >= 131 && number <= 155) || number === 252) {
    return PokemonType.Fighting;
  }
  if ((number >= 156 && number <= 179) || number === 253 || number === 271) {
    return PokemonType.Darkness;
  }
  if ((number >= 180 && number <= 192) || (number >= 254 && number <= 255)) {
    return PokemonType.Metal;
  }
  if (number >= 193 && number <= 198) {
    return PokemonType.Dragon;
  }
  if ((number >= 199 && number <= 223) || (number >= 256 && number <= 257) || number === 272) {
    return PokemonType.Colorless;
  }

  return undefined;
}

function createSlug(name: string, cardNumber: string): string {
  const normalizedName = name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

  const number = cardNumber.split("/")[0].toLowerCase();
  return `${normalizedName}-${number}`;
}

