function getPokemonType(cardNumber: string): PokemonType | undefined {
  const number = Number.parseInt(cardNumber, 10);
  if ((number >= 1 && number <= 19) || number === 160 || number === 199 || number === 223) return PokemonType.Grass;
  if ((number >= 20 && number <= 28) || (number >= 161 && number <= 162) || (number >= 200 && number <= 201)) return PokemonType.Fire;
  if ((number >= 29 && number <= 46) || (number >= 163 && number <= 164) || (number >= 202 && number <= 203) || number === 231) return PokemonType.Water;
  if ((number >= 47 && number <= 53) || number === 165) return PokemonType.Lightning;
  if ((number >= 54 && number <= 75) || (number >= 166 && number <= 172) || (number >= 204 && number <= 205) || number === 232) return PokemonType.Psychic;
  if ((number >= 76 && number <= 93) || (number >= 173 && number <= 175) || number === 206 || number === 233) return PokemonType.Fighting;
  if ((number >= 94 && number <= 108) || (number >= 176 && number <= 180) || number === 207) return PokemonType.Darkness;
  if ((number >= 109 && number <= 114) || number === 181 || number === 208 || number === 224) return PokemonType.Metal;
  if ((number >= 115 && number <= 128) || (number >= 182 && number <= 185) || number === 209 || number === 225) return PokemonType.Colorless;
  return undefined;
}

function createSlug(name: string, cardNumber: string): string {
  const normalizedName = name.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const number = cardNumber.split("/")[0].toLowerCase();
  return `${normalizedName}-${number}`;
}

