function getPokemonType(cardNumber: string): PokemonType | undefined {
  const number = Number.parseInt(cardNumber, 10);
  if ((number >= 1 && number <= 17) || (number >= 166 && number <= 168) || (number >= 204 && number <= 206)) return PokemonType.Grass;
  if ((number >= 18 && number <= 23) || (number >= 169 && number <= 170)) return PokemonType.Fire;
  if ((number >= 24 && number <= 48) || (number >= 171 && number <= 176) || (number >= 207 && number <= 209) || number === 226 || number === 227) return PokemonType.Water;
  if ((number >= 49 && number <= 60) || (number >= 177 && number <= 178) || number === 210 || number === 235) return PokemonType.Lightning;
  if ((number >= 61 && number <= 80) || (number >= 179 && number <= 184) || (number >= 211 && number <= 212) || number === 228) return PokemonType.Psychic;
  if ((number >= 81 && number <= 92) || (number >= 185 && number <= 187) || number === 213) return PokemonType.Fighting;
  if ((number >= 93 && number <= 105) || (number >= 188 && number <= 190) || (number >= 214 && number <= 216) || number === 236) return PokemonType.Darkness;
  if ((number >= 106 && number <= 124) || (number >= 191 && number <= 198) || (number >= 217 && number <= 221)) return PokemonType.Dragon;
  if ((number >= 125 && number <= 140)) return PokemonType.Colorless;
  if (number === 237) return PokemonType.Metal;
  return undefined;
}

function createSlug(name: string, cardNumber: string): string {
  const normalizedName = name.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const number = cardNumber.split("/")[0].toLowerCase();
  return `${normalizedName}-${number}`;
}

